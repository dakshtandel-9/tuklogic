"""Rewrite the captured site to its downloaded media, without network access."""
import html
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'public'
CDN = 'https://dxmdwxi6k7ogv.cloudfront.net/public'
manifest = json.loads((ROOT / 'reference/local-assets.json').read_text())
external = {url: local for url, local in manifest['assets'].items() if not url.startswith(CDN)}


def localize(text):
    for url, local in external.items():
        text = text.replace(url, local).replace(html.escape(url, quote=False), local)
    text = text.replace(CDN, '/offline')
    text = text.replace('/icons/placeholder-icon.svg', '/icons/gradient-blue-dot.svg')
    text = text.replace('/templates-images/icons/gradient-blue-dot.svg', '/icons/gradient-blue-dot.svg')
    text = text.replace('/favicon-128.png', '/favicon-196x196.png')
    text = text.replace('url(/templates-images/', 'url(/offline/templates-images/')
    text = re.sub(r'<link\b(?=[^>]*rel="(?:preconnect|dns-prefetch)")[^>]*>', '', text)
    text = text.replace('https://dxmdwxi6k7ogv.cloudfront.net', '')
    text = text.replace('https://fonts.gstatic.com', '')
    return text


# Include existing media selected by dynamic filenames.
for folder in ('images', 'icons'):
    for source in (PUBLIC / folder).rglob('*'):
        if source.is_file():
            target = PUBLIC / 'offline' / source.relative_to(PUBLIC)
            if not target.exists():
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)

for path in list((PUBLIC / 'assets').glob('*')) + list((PUBLIC / 'locales').rglob('*.json')):
    original = path.read_text()
    updated = localize(original)
    if path.name == 'ui-components-krT5pv9S.js':
        updated = updated.replace('e||n.startsWith("http")', 'e||n.startsWith("/offline/")||n.startsWith("http")')
        updated = updated.replace('const r=`${Hg}${n}`', 'const r=n.startsWith("/offline/")?n:`${Hg}${n}`')
        updated = updated.replace('i=e.includes(".com")||e.includes("http")?', 'i=e.startsWith("/offline/")||e.includes(".com")||e.includes("http")?')
    if path.name == 'IntroScene-BHFZ14jm.js':
        updated = updated.replace('B(e.src.replace(y,""))', 'B("/scenes/desktop/eh/intro.mp4")')
    if path.name == 'main-B2LH-fDE.js':
        # Forms were already disconnected; do not initialize a remote captcha.
        updated = updated.replace('o2=function(s){var i=s.render', 'o2=function(s){return;var i=s.render')
    if path.name == 'contact-BzFsy9fp.js':
        # Keep the address and explicit map links; avoid the hosted Maps SDK.
        updated = re.sub(r'vt=\(\{center:t\}\)=>.*?,bt=\[',
            'vt=()=>r.jsx("img",{src:"/offline/images/crystal-map.png",alt:"Office locations",className:"h-[30rem] w-full object-contain"}),bt=[', updated, count=1)
    if updated != original:
        path.write_text(updated)

pages_path = ROOT / 'lib/pages.json'
pages = json.loads(pages_path.read_text())
# Case studies are authored in lib/case-studies.ts using the approved catalog,
# and services are the experience in lib/services-page.ts. A capture refresh
# must not restore the retired agency pages.
pages = {route: localize(page) for route, page in pages.items()
         if not re.match(r'^/(?:en|ar)/(?:case-studies|digital-services)(?:/|$)', route)}
pages_path.write_text(json.dumps(pages, separators=(',', ':')))
# Import one document per request instead of compiling the entire 28 MB capture
# into the development worker whenever any page is opened or edited.
page_dir = ROOT / 'lib/offline-pages'
page_dir.mkdir(exist_ok=True)
for legacy_page in [*page_dir.glob('*__case-studies*.json'), *page_dir.glob('*__digital-services*.json')]:
    legacy_page.unlink()
loaders = []
for route, document in sorted(pages.items()):
    name = route.strip('/').replace('/', '__') + '.json'
    (page_dir / name).write_text(json.dumps(document))
    loaders.append(f'  {json.dumps(route)}: () => import("./offline-pages/{name}").then(module => module.default),')
(ROOT / 'lib/page-loaders.ts').write_text(
    '// Generated by scripts/prepare-offline.py. Each page loads independently.\n'
    'export const pageLoaders: Record<string, () => Promise<string>> = {\n'
    + '\n'.join(loaders) + '\n};\n')
content_path = ROOT / 'reference/api/offline-content.json'
if content_path.exists():
    content_path.write_text(localize(content_path.read_text()))
print(f'Localized {len(pages)} captured pages and their frontend assets.')
subprocess.run(['node', str(ROOT / 'scripts/patch-site-seo.mjs')], check=True)
